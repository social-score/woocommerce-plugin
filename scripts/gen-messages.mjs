// Generates includes/class-messages.php from plugin-core's English source strings so each one is translatable.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(process.argv[2], 'utf8');
const rows = [...src.matchAll(/readonly '([^']+)': "((?:[^"\\]|\\.)*)";/g)];
if (rows.length < 50) throw new Error('too few messages: ' + rows.length);
const width = Math.max(...rows.map(([, k]) => k.length)) + 2;
const php = (s) => s.replace(/\\"/g, '"').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const out = `<?php
/**
 * Translatable texts of the shared SocialScore screens. Generated by scripts/gen-messages.mjs from
 * @socialscore/plugin-core; do not edit by hand.
 *
 * @package SocialScore
 */

namespace SocialScore;

defined( 'ABSPATH' ) || exit;

/**
 * Message catalogue handed to the React screens as \`PluginHost.t\` input.
 */
class Messages {

	/**
	 * All texts by key, translated for the current locale.
	 *
	 * @return array<string,string>
	 */
	public static function all() {
		return array(
${rows.map(([, k, v]) => `\t\t\t${("'" + k + "'").padEnd(width)} => __( '${php(v)}', 'socialscore' ),`).join('\n')}
		);
	}
}
`;
writeFileSync(process.argv[3], out);
console.log('wrote', rows.length, 'messages');
